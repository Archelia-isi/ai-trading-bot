                "\n",
                "def elabora_e_fondi(df_prezzi, is_crypto=True):\n",
                "    print(\"Simulazione pipeline NLP (Batching su A100)...\")\n",
                "    \n",
                "    # In produzione, qui scaricheremmo 16M di tweet da Kaggle o HuggingFace.\n",
                "    # Per questa demo, generiamo tweet sintetici realistici allineati ai nostri prezzi.\n",
                "    \n",
                "    # Creiamo un dataset di news casuali sparse nel tempo del df_prezzi\n",
                "    np.random.seed(42)\n",
                "    num_news = len(df_prezzi) // 2\n",
                "    news_dates = df_prezzi['Datetime'].sample(n=num_news, replace=True).values\n",
                "    \n",
                "    df_news = pd.DataFrame({'Date': news_dates})\n",
                "    # Simuliamo il BERT score grezzo tra -1 e +1\n",
                "    df_news['Raw_BERT_Score'] = np.random.normal(0, 0.5, num_news)\n",
                "    \n",
                "    # IL FIX SOTA: Resampling & Magnitudo\n",
                "    print(\"Eseguendo Resampling M15 per aggregazione volumetrica...\")\n",
                "    df_news.set_index('Date', inplace=True)\n",
                "    timeframe = '15min' if is_crypto else '1min'\n",
                "    \n",
                "    df_news_agg = df_news.resample(timeframe).agg(\n",
                "        Raw_Shock=('Raw_BERT_Score', 'sum'),\n",
                "        News_Volume=('Raw_BERT_Score', 'count')\n",
                "    ).reset_index()\n",
                "    \n",
                "    df_news_agg.fillna(0, inplace=True)\n",
                "    \n",
                "    # Unione Asincrona Corretta\n",
                "    df_finale = pd.merge_asof(\n",
                "        df_prezzi, \n",
                "        df_news_agg, \n",
                "        left_on='Datetime', \n",
                "        right_on='Date', \n",
                "        direction='backward'\n",
                "    )\n",
                "    df_finale.drop(columns=['Date'], inplace=True, errors='ignore')\n",
                "    df_finale.fillna(0, inplace=True)\n",
                "    \n",
                "    # 5. Ricalcolo EMA e Feature Ingegneria\n",
                "    df_finale['Sentiment_EMA'] = df_finale['Raw_Shock'].ewm(span=14, adjust=False).mean()\n",
                "    \n",
                "    # Tempo trascorso dall'ultima news (Decadimento)\n",
                "    df_finale['Time_Since_News'] = df_finale.groupby(df_finale['Raw_Shock'] != 0).cumcount()\n",
